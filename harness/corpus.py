"""Corpus manifest loading and validation."""

from __future__ import annotations

import hashlib
import json
import sys
from dataclasses import dataclass, field
from pathlib import Path

import yaml

REQUIRED = ("id", "path", "class", "source", "split")


@dataclass
class Item:
    id: str
    path: Path
    cls: str
    source: str
    split: str
    sha256: str | None = None
    tags: list[str] = field(default_factory=list)
    licence: str | None = None

    @property
    def exists(self) -> bool:
        return self.path.exists()

    def actual_sha256(self) -> str | None:
        if not self.exists:
            return None
        h = hashlib.sha256()
        with open(self.path, "rb") as fh:
            for chunk in iter(lambda: fh.read(1 << 20), b""):
                h.update(chunk)
        return h.hexdigest()


def load(manifest: Path) -> tuple[int, list[Item]]:
    data = yaml.safe_load(manifest.read_text()) or {}
    base = manifest.parent
    items: list[Item] = []
    seen: set[str] = set()

    raw_items = list(data.get("items") or [])
    # Derived items live beside the manifest in their own file so that
    # regenerating the fetched manifest does not lose them.
    derived = manifest.parent / "derived.yaml"
    if derived.exists():
        extra = (yaml.safe_load(derived.read_text()) or {}).get("items") or []
        raw_items.extend(extra)

    for raw in raw_items:
        missing = [k for k in REQUIRED if not raw.get(k)]
        if missing:
            raise ValueError(f"item {raw.get('id', '?')} missing {missing}")
        if raw["id"] in seen:
            raise ValueError(f"duplicate id {raw['id']}")
        seen.add(raw["id"])
        items.append(
            Item(
                id=raw["id"],
                path=(base / raw["path"]).resolve(),
                cls=raw["class"],
                source=raw["source"],
                split=raw["split"],
                sha256=raw.get("sha256"),
                tags=list(raw.get("tags") or []),
                licence=raw.get("licence"),
            )
        )
    return int(data.get("corpus_version", 0)), items


def filter_split(items: list[Item], split: str = "all") -> list[Item]:
    if not split or split == "all":
        return items
    return [item for item in items if item.split == split]


def holdout_digest(items: list[Item]) -> str:
    """Fingerprint of the holdout set, so it can be checked for drift.

    Published scores must come from documents that were never used to tune the
    measurement. Freezing the digest is what makes that auditable.
    """
    holdout = sorted((i.id, i.sha256 or "") for i in items if i.split == "holdout")
    payload = json.dumps(holdout, separators=(",", ":")).encode()
    return hashlib.sha256(payload).hexdigest()


def load_overrides(path: Path) -> dict[str, dict]:
    """Per-document tolerance overrides.

    Kept in a separate file because the manifest is generated by the fetcher
    and would lose hand-written entries on the next run.
    """
    if not path.exists():
        return {}
    data = yaml.safe_load(path.read_text()) or {}
    return {str(k): dict(v or {}) for k, v in (data.get("items") or {}).items()}


def validate(manifest: Path, verbose: bool = True, strict: bool = False) -> int:
    """Return a process exit code. Warnings do not fail the check."""
    version, items = load(manifest)
    problems = 0
    if verbose:
        print(f"corpus_version={version} items={len(items)}")
    for item in items:
        if not item.exists:
            print(f"  MISSING FILE  {item.id}: {item.path}", file=sys.stderr)
            problems += 1
            continue
        if item.sha256 and item.sha256 != "0" * 64:
            actual = item.actual_sha256()
            if actual != item.sha256:
                print(f"  HASH MISMATCH {item.id}: {actual}", file=sys.stderr)
                problems += 1
        if not item.licence:
            print(f"  NO LICENCE    {item.id}", file=sys.stderr)
            if strict:
                problems += 1
    if verbose:
        print(f"problems={problems}")
    return 0 if problems == 0 else 1
